/** Окно, за которое считаются развороты мыши. */
export const SHAKE_WINDOW_MS = 600;

/**
 * Отрезки короче порога не учитываем: дрожание руки и субпиксельный шум не
 * должны выглядеть как развороты. Отрезок при этом копится, а не выбрасывается,
 * иначе медленное движение никогда не дошло бы до порога.
 */
export const MIN_SEGMENT_PX = 8;

/** Мёртвая зона для знака отдельной оси внутри отрезка. */
export const MIN_AXIS_PX = MIN_SEGMENT_PX / 2;

/** Ниже этой средней скорости считаем, что мастер просто водит мышью. */
export const MIN_SPEED_PX_PER_SEC = 500;

/** Сколько разворотов в окне включает ореол и сколько раздувает его до конца. */
export const TURNS_TO_TRIGGER = 3;
export const TURNS_FOR_MAX = 6;

/**
 * Растём быстро, гаснем медленно и не сразу: мастер должен успеть найти курсор
 * глазами уже после того, как перестал махать мышью.
 */
export const RISE_MS = 120;
export const HOLD_MS = 400;
export const FADE_MS = 600;

/** Размер ореола на минимуме — в долях от размера из CursorHalo.scss. */
export const MIN_SCALE = 0.45;
